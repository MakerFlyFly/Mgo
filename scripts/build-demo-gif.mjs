import sharp from "sharp";
import { resolve } from "node:path";
import { readFile } from "node:fs/promises";
const frames = Array.from({ length: 20 }, (_, index) => resolve("tmp", "polish-frames", `${String(index).padStart(2, "0")}.png`));
const { capturedAt } = JSON.parse(await readFile(resolve("tmp", "polish-frames", "timing.json"), "utf8"));
if (capturedAt.length !== frames.length || !capturedAt.every(Number.isFinite)) throw new Error("Recording timestamps do not match the frames");
const delays = capturedAt.map((time, index) => index === frames.length - 1 ? 2400 : Math.max(50, Math.min(3000, capturedAt[index + 1] - time)));
await sharp(frames, { animated: true, join: { animated: true } }).resize({ width: 960 }).gif({ loop: 0, delay: delays, effort: 5, colours: 128 }).toFile("docs/demo.gif");
const metadata = await sharp("docs/demo.gif", { animated: true }).metadata();
console.log(JSON.stringify({ file: "docs/demo.gif", frames: metadata.pages, width: metadata.width, frameHeight: metadata.pageHeight }));
if (metadata.pages !== frames.length) throw new Error("The recording did not retain all frames");
